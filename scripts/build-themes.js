#!/usr/bin/env node

/**
 * Writes what the page needs of the built-in themes, from the theme data in
 * src/utils/theme/builtin/: one stylesheet a theme (src/styles/themes/),
 * the stylesheet that gathers them (src/styles/themes.css), and the script
 * the page runs before it first paints (src/utils/theme/boot.js).
 *
 *   node scripts/build-themes.js          write the files
 *   node scripts/build-themes.js --check  exit 1 when a file is out of date
 *
 * A test (src/utils/theme/generated.test.js) fails when they are out of date.
 * @module scripts/build-themes
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { BUILTIN_THEMES, SYSTEM_THEMES, THEME_TABLE } from '../src/utils/theme/builtin/index.js';
import { STORED, paintTheme, pickTheme } from '../src/utils/theme/preference.js';
import { effectiveTheme } from '../src/utils/theme/resolve.js';
import { themeRule, themeVariables } from '../src/utils/theme/variables.js';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const NOTE = 'Generated by scripts/build-themes.js';

/**
 * @param {import('../src/utils/theme/model.js').Theme} theme
 * @returns {string} The theme's stylesheet. The theme a light system gets
 *   is also what a page without `data-theme` shows
 */
function themeSheet(theme) {
  const selector = `[data-theme='${theme.id}']`;
  const fallback = theme.id === SYSTEM_THEMES.light ? ':root,\n' : '';
  const rule = themeRule(themeVariables(effectiveTheme(theme)), `${fallback}${selector}`);
  return `/* ${NOTE} from src/utils/theme/builtin/${theme.id}.js — do not edit. */\n\n${rule}`;
}

/** @returns {string} The stylesheet index.html links: every theme, the fallback first */
function gatherSheet() {
  const first = BUILTIN_THEMES.filter((theme) => theme.id === SYSTEM_THEMES.light);
  const rest = BUILTIN_THEMES.filter((theme) => theme.id !== SYSTEM_THEMES.light);
  const imports = [...first, ...rest].map((theme) => `@import './themes/${theme.id}.css';`);
  const head =
    `/* ${NOTE} — do not edit. The colours of the built-in themes, one\n` +
    '   file a theme; any other theme is set on the page at run time\n' +
    '   (docs/app-spec/THEMES.md). */';
  return `${head}\n${imports.join('\n')}\n`;
}

/**
 * @param {Record<string, string>} object
 * @param {string} pad
 * @returns {string} An object literal, one property a line
 */
function literal(object, pad) {
  const key = (/** @type {string} */ name) => (/^[a-z_$][\w$]*$/i.test(name) ? name : `'${name}'`);
  const lines = Object.entries(object).map(([name, value]) => `${pad}  ${key(name)}: '${value}',`);
  return `{\n${lines.join('\n')}\n${pad}}`;
}

/** @returns {string} The page's first script: a classic script, not a module */
function bootScript() {
  const inner = (/** @type {Function} */ fn) => fn.toString().replace(/\n/g, '\n  ');
  return `/*
 * ${NOTE} — do not edit. The page's first script
 * (src/index.html), a classic script: it puts the theme on the page before
 * anything is painted, so the page never flashes another one. The two
 * functions are those of src/utils/theme/preference.js, as the app uses them.
 */
{
  const table = {
    schemes: ${literal(THEME_TABLE.schemes, '    ')},
    system: ${literal(THEME_TABLE.system, '    ')},
  };
  const pickTheme = ${inner(pickTheme)};
  const paintTheme = ${inner(paintTheme)};
  const stored = (key) => {
    try {
      return JSON.parse(localStorage.getItem(key)) || {};
    } catch (err) {
      console.warn('[theme] nothing usable is stored:', err.message);
      return {};
    }
  };
  const system = {
    dark: matchMedia('(prefers-color-scheme: dark)').matches,
    contrast: matchMedia('(prefers-contrast: more)').matches,
  };
  const preference = stored('${STORED.state}').theme;
  paintTheme(document.documentElement, pickTheme(preference, system, table, stored('${STORED.theme}')));
}
`;
}

/**
 * Everything this script writes.
 * @returns {Record<string, string>} Path from the repository's root → content
 */
export function themeFiles() {
  const sheets = BUILTIN_THEMES.map((theme) => [`src/styles/themes/${theme.id}.css`, themeSheet(theme)]);
  return {
    'src/styles/themes.css': gatherSheet(),
    ...Object.fromEntries(sheets),
    'src/utils/theme/boot.js': bootScript(),
  };
}

/**
 * @returns {string[]} The files that are missing or differ from what would be written
 */
export function staleFiles() {
  return Object.entries(themeFiles())
    .filter(([path, content]) => {
      const file = resolve(ROOT, path);
      return !existsSync(file) || readFileSync(file, 'utf8') !== content;
    })
    .map(([path]) => path);
}

const isEntryPoint = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (isEntryPoint) {
  const stale = staleFiles();
  if (process.argv.includes('--check')) {
    if (stale.length) console.error(`Out of date: ${stale.join(', ')} — run node scripts/build-themes.js`);
    process.exit(stale.length ? 1 : 0);
  }
  for (const [path, content] of Object.entries(themeFiles())) {
    mkdirSync(dirname(resolve(ROOT, path)), { recursive: true });
    writeFileSync(resolve(ROOT, path), content);
  }
  console.log(`✓ Built ${BUILTIN_THEMES.length} themes → src/styles/themes/ (${stale.length} changed)`);
}
